// go-print-ranges writes crates/protowire-pxf/src/go_print.rs: the code
// points Go's strconv.IsPrint calls printable, as sorted inclusive ranges.
// protowire-go names an illegal character with %q, which escapes every
// character IsPrint refuses, so the port needs the same set. Run it
// through scripts/gen-go-print-ranges.sh.
package main

import (
	"fmt"
	"os"
	"runtime"
	"strconv"
	"unicode"
)

func main() {
	type span struct{ lo, hi rune }
	var spans []span
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !strconv.IsPrint(r) {
			continue
		}
		if n := len(spans); n > 0 && spans[n-1].hi == r-1 {
			spans[n-1].hi = r
		} else {
			spans = append(spans, span{r, r})
		}
	}
	w := os.Stdout
	fmt.Fprintf(w, "// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 TrendVidia, LLC.\n")
	fmt.Fprintf(w, "//! Generated by scripts/gen-go-print-ranges.sh from %s (Unicode %s). Do not edit.\n//!\n", runtime.Version(), unicode.Version)
	fmt.Fprintf(w, "//! The code points Go's `strconv.IsPrint` calls printable, as sorted\n//! inclusive ranges: protowire-go names an illegal character with `%%q`,\n//! which escapes every other code point.\n\n")
	fmt.Fprintf(w, "pub(crate) const GO_PRINT_RANGES: &[(u32, u32)] = &[\n")
	for _, s := range spans {
		fmt.Fprintf(w, "    (0x%x, 0x%x),\n", s.lo, s.hi)
	}
	fmt.Fprintf(w, "];\n")
}
